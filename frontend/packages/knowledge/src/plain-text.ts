/**
 * markdown 源码 → 卡片上"读得懂的一句话"。
 *
 * <p>列表卡片上的摘要是**正文前 200 字**，里面带着 markdown 记号（`##`、`**`、链接语法、
 * 代码围栏）。卡片要的是一句话，所以把最常见的那几种记号抹掉。
 *
 * <p><b>刻意不渲染 markdown</b>：摘要往往从半个表格或半个代码块开始，
 * 渲染出来只会比抹掉记号更难看。
 *
 * <p>放在共享包里，是因为学习者端的四个页面（首页、分类页、条目列表、条目列表的最近更新）
 * 都要用同一份规则——各写一份的后果是同一个条目在不同页面上显示成不同的样子。
 */
export function plainText(markdown: string): string {
  return markdown
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 行首记号：标题的 #、引用的 >、列表的 -/*/+。**只在行首匹配**。
    .replace(/^[ \t]*(?:#{1,6}|>|[-*+])[ \t]+/gm, '')
    // 成对的加粗记号。**刻意不处理单个 `*` 与 `_`**：斜体在这些笔记里很少见，
    // 而全局删这两个字符会把编程内容吃坏——`snake_case` 会变成 `snakecase`，
    // 这正是这一版之前的行为（写测试时才发现的）。
    .replace(/(\*\*|__)(.+?)\1/g, '$2')
    .replace(/`/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}
